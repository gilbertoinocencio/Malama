// ============================================================
// Malama — Empirical Cases Generator
// ============================================================
// Learns from finished quarterly plans: aggregates anonymized
// outcomes into cohort-level case patterns and stores them in
// empirical_cases (the agent's empirical memory).
//
// Privacy guarantees enforced here:
//   * Cohorts only (goal | sex | age band): a case is emitted only
//     when >= MIN_COHORT_SIZE users share the profile (k-anonymity).
//   * Input to the LLM is exclusively structured/aggregated data and
//     plan strategies generated by the AI itself — never user free text,
//     names, dates or identifiers.
//
// Usage: node scripts/generate-empirical-cases.js
// ============================================================

import dotenv from 'dotenv';
import { createClient } from '@supabase/supabase-js';

dotenv.config({ path: '.env.local' });
dotenv.config({ path: '.env' });

const supabaseUrl = process.env.VITE_SUPABASE_URL || process.env.SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
const geminiApiKey = process.env.GEMINI_API_KEY || process.env.VITE_GEMINI_API_KEY;

if (!supabaseUrl || !supabaseKey || !geminiApiKey) {
    console.error('Missing env vars: need VITE_SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, GEMINI_API_KEY.');
    process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);

const MIN_COHORT_SIZE = 3;          // k-anonymity threshold
const MIN_WEIGHT_LOGS = 2;          // need start + end weight to compute outcome
const MIN_TRACKING_DAYS = 30;       // weight logs must span at least this many days
const EMBEDDING_MODEL = 'gemini-embedding-001';
const EMBEDDING_DIMENSIONS = 768;   // must match empirical_cases.embedding vector(768)
const TEXT_MODEL = 'gemini-2.5-flash';
const GEMINI_BASE = 'https://generativelanguage.googleapis.com/v1beta/models';

// ── Gemini helpers ──────────────────────────────────────────

async function embedText(text) {
    const res = await fetch(`${GEMINI_BASE}/${EMBEDDING_MODEL}:embedContent?key=${geminiApiKey}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
            model: `models/${EMBEDDING_MODEL}`,
            content: { parts: [{ text }] },
            outputDimensionality: EMBEDDING_DIMENSIONS,
        }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error?.message || `HTTP ${res.status}`);
    return data.embedding.values;
}

async function generateText(prompt) {
    const res = await fetch(`${GEMINI_BASE}/${TEXT_MODEL}:generateContent?key=${geminiApiKey}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ contents: [{ role: 'user', parts: [{ text: prompt }] }] }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error?.message || `HTTP ${res.status}`);
    const parts = data.candidates?.[0]?.content?.parts || [];
    return parts.filter(p => !p.thought && typeof p.text === 'string').map(p => p.text).join('');
}

// ── Anonymization helpers ───────────────────────────────────

function ageBand(age) {
    if (!age || age < 18) return 'na';
    if (age < 30) return '18-29';
    if (age < 40) return '30-39';
    if (age < 50) return '40-49';
    if (age < 60) return '50-59';
    return '60+';
}

function computeAge(dateOfBirth) {
    if (!dateOfBirth) return null;
    const birth = new Date(dateOfBirth);
    const today = new Date();
    let age = today.getFullYear() - birth.getFullYear();
    const m = today.getMonth() - birth.getMonth();
    if (m < 0 || (m === 0 && today.getDate() < birth.getDate())) age--;
    return age;
}

const GOAL_LABELS = {
    aesthetic: 'emagrecimento / estética',
    performance: 'performance / ganho de massa',
    health: 'saúde metabólica',
};

// ── Outcome classification (v1 heuristic) ───────────────────

function classifyOutcome(goal, weightChangePct, adherencePct) {
    if (goal === 'aesthetic') {
        if (weightChangePct <= -3) return 'success';
        if (weightChangePct <= -0.5) return 'partial';
        return 'failure';
    }
    if (goal === 'performance') {
        if (weightChangePct >= 2) return 'success';
        if (weightChangePct >= 0.5) return 'partial';
        return 'failure';
    }
    // health: stability + engagement
    if (Math.abs(weightChangePct) <= 2 && adherencePct >= 40) return 'success';
    if (adherencePct >= 20) return 'partial';
    return 'failure';
}

// ── Data collection ─────────────────────────────────────────

async function collectOutcomes() {
    const today = new Date().toISOString().slice(0, 10);

    const { data: plans, error: plansErr } = await supabase
        .from('quarterly_plans')
        .select('id, user_id, start_date, end_date, content')
        .lt('end_date', today);
    if (plansErr) throw plansErr;

    console.log(`Found ${plans.length} finished plans.`);
    const outcomes = [];

    for (const plan of plans) {
        const { data: profile } = await supabase
            .from('profiles')
            .select('goal, gender, date_of_birth, age, biotype, activity_level')
            .eq('id', plan.user_id)
            .single();
        if (!profile?.goal || !profile?.gender) continue; // cohort needs goal + sex

        const age = profile.age || computeAge(profile.date_of_birth);

        // Weight trajectory within the plan window (± 7 days of margin)
        const windowStart = new Date(plan.start_date);
        windowStart.setDate(windowStart.getDate() - 7);
        const windowEnd = new Date(plan.end_date);
        windowEnd.setDate(windowEnd.getDate() + 7);

        const { data: weights } = await supabase
            .from('weight_logs')
            .select('weight_kg, logged_at')
            .eq('user_id', plan.user_id)
            .gte('logged_at', windowStart.toISOString())
            .lte('logged_at', windowEnd.toISOString())
            .order('logged_at', { ascending: true });

        if (!weights || weights.length < MIN_WEIGHT_LOGS) continue;
        const first = weights[0];
        const last = weights[weights.length - 1];
        const spanDays = (new Date(last.logged_at) - new Date(first.logged_at)) / 86400000;
        if (spanDays < MIN_TRACKING_DAYS) continue;

        const weightChangePct = ((last.weight_kg - first.weight_kg) / first.weight_kg) * 100;

        // Adherence: days with any daily log during the plan
        const { count: logDays } = await supabase
            .from('daily_logs')
            .select('id', { count: 'exact', head: true })
            .eq('user_id', plan.user_id)
            .gte('date', plan.start_date)
            .lte('date', plan.end_date);

        const planDays = (new Date(plan.end_date) - new Date(plan.start_date)) / 86400000;
        const adherencePct = planDays > 0 ? Math.min(100, ((logDays || 0) / planDays) * 100) : 0;

        // Strategies: bullets/titles from the AI-generated plan only (no user text)
        const strategies = (plan.content?.phases || [])
            .flatMap(p => p.bullets || [])
            .slice(0, 15);

        outcomes.push({
            cohortKey: `${profile.goal}|${profile.gender}|${ageBand(age)}`,
            goal: profile.goal,
            outcome: classifyOutcome(profile.goal, weightChangePct, adherencePct),
            weightChangePct: Number(weightChangePct.toFixed(1)),
            adherencePct: Number(adherencePct.toFixed(0)),
            activityLevel: profile.activity_level || 'na',
            biotype: profile.biotype || 'na',
            strategies,
        });
    }

    return outcomes;
}

// ── Case generation per cohort ──────────────────────────────

async function generateCaseForCohort(cohortKey, members) {
    const [goal, sex, band] = cohortKey.split('|');
    const byOutcome = { success: [], partial: [], failure: [] };
    members.forEach(m => byOutcome[m.outcome].push(m));

    const avg = (arr, f) => arr.length ? (arr.reduce((s, m) => s + f(m), 0) / arr.length).toFixed(1) : null;

    const metrics = {
        cohort_size: members.length,
        success_count: byOutcome.success.length,
        partial_count: byOutcome.partial.length,
        failure_count: byOutcome.failure.length,
        avg_weight_change_pct_success: avg(byOutcome.success, m => m.weightChangePct),
        avg_weight_change_pct_failure: avg(byOutcome.failure, m => m.weightChangePct),
        avg_adherence_pct_success: avg(byOutcome.success, m => m.adherencePct),
        avg_adherence_pct_failure: avg(byOutcome.failure, m => m.adherencePct),
    };

    const dominantOutcome =
        byOutcome.success.length > members.length / 2 ? 'success' :
        byOutcome.failure.length > members.length / 2 ? 'failure' : 'mixed';

    const successStrategies = [...new Set(byOutcome.success.flatMap(m => m.strategies))].slice(0, 10);
    const failureStrategies = [...new Set(byOutcome.failure.flatMap(m => m.strategies))].slice(0, 10);

    const prompt = `
Você é uma nutricionista clínica escrevendo um REGISTRO DE EXPERIÊNCIA EMPÍRICA para a base de conhecimento interna de uma agente de IA.

Escreva um padrão de caso clínico agregado e 100% anônimo, em português, com base EXCLUSIVAMENTE nos dados agregados abaixo. NUNCA invente nomes, datas, cidades ou detalhes individuais. Refira-se sempre ao grupo ("pacientes deste perfil"), nunca a indivíduos.

PERFIL DA COORTE:
- Objetivo: ${GOAL_LABELS[goal] || goal}
- Sexo: ${sex === 'male' ? 'masculino' : sex === 'female' ? 'feminino' : sex}
- Faixa etária: ${band}
- Tamanho da coorte: ${members.length} pacientes

DESFECHOS OBSERVADOS (planos de 3 meses):
- Sucesso: ${metrics.success_count} | Parcial: ${metrics.partial_count} | Insucesso: ${metrics.failure_count}
- Variação média de peso (grupo sucesso): ${metrics.avg_weight_change_pct_success ?? 'N/A'}%
- Variação média de peso (grupo insucesso): ${metrics.avg_weight_change_pct_failure ?? 'N/A'}%
- Adesão média ao registro diário (sucesso): ${metrics.avg_adherence_pct_success ?? 'N/A'}%
- Adesão média ao registro diário (insucesso): ${metrics.avg_adherence_pct_failure ?? 'N/A'}%

ESTRATÉGIAS PRESENTES NOS PLANOS DO GRUPO SUCESSO:
${successStrategies.map(s => `- ${s}`).join('\n') || '- (sem dados)'}

ESTRATÉGIAS PRESENTES NOS PLANOS DO GRUPO INSUCESSO:
${failureStrategies.map(s => `- ${s}`).join('\n') || '- (sem dados)'}

FORMATO (máx. 250 palavras):
1. Perfil do grupo (1 frase)
2. O que os dados sugerem que funcionou e por quê
3. O que esteve associado a insucesso
4. Aprendizado prático para novos pacientes deste perfil (2-3 recomendações acionáveis)

Seja honesta sobre limitações: coorte pequena = padrões sugestivos, não conclusivos.
`;

    const summary = await generateText(prompt);
    const embedding = await embedText(
        `Caso empírico: ${GOAL_LABELS[goal] || goal}, sexo ${sex}, ${band} anos.\n${summary}`
    );

    // Replace previous case for this cohort (regenerable pipeline)
    await supabase.from('empirical_cases').delete().eq('cohort_key', cohortKey);
    const { error } = await supabase.from('empirical_cases').insert({
        cohort_key: cohortKey,
        cohort_size: members.length,
        outcome: dominantOutcome,
        summary,
        metrics,
        embedding,
    });
    if (error) throw error;

    console.log(`✓ Case generated for cohort ${cohortKey} (${members.length} users, ${dominantOutcome})`);
}

// ── Main ────────────────────────────────────────────────────

async function main() {
    const outcomes = await collectOutcomes();
    console.log(`${outcomes.length} plans with measurable outcomes.`);

    const cohorts = {};
    outcomes.forEach(o => {
        (cohorts[o.cohortKey] = cohorts[o.cohortKey] || []).push(o);
    });

    let generated = 0;
    for (const [key, members] of Object.entries(cohorts)) {
        if (members.length < MIN_COHORT_SIZE) {
            console.log(`- Cohort ${key}: only ${members.length} user(s), below k=${MIN_COHORT_SIZE}. Skipped (privacy).`);
            continue;
        }
        try {
            await generateCaseForCohort(key, members);
            generated++;
        } catch (err) {
            console.error(`Failed cohort ${key}:`, err.message);
        }
    }

    console.log(`\nDone. ${generated} empirical case(s) generated/updated.`);
}

main();
